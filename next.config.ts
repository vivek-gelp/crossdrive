import type { NextConfig } from "next";

// Baseline browser hardening for every route. Routes that set a stricter policy themselves (the OAuth consent
// page) keep theirs; these are the floor. Never use `Referrer-Policy: no-referrer` on a page with a form: Chrome then
// sends `Origin: null` on the POST. The consent page sends `strict-origin` and repeats it in a meta tag, so its
// effective policy does not depend on which of the two Referrer-Policy headers survives.
const SECURITY_HEADERS = [
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=()" },
];

const ICON_CACHE = "public, max-age=86400, stale-while-revalidate=604800";

const nextConfig: NextConfig = {
  // Heavy parsers stay external so Node loads them as published; unpdf's pdf.js build needs no browser globals.
  serverExternalPackages: ["unpdf", "mammoth", "xlsx"],
  async headers() {
    return [
      { source: "/:path*", headers: SECURITY_HEADERS },
      // Icons (generated by scripts/make-icons.mjs) keep unversioned URLs that favicon services and MCP clients
      // fetch directly, so cache for a day rather than forever. Content-Type comes from the file extension.
      {
        source: "/:file(favicon.ico|icon.svg|icon-32.png|icon-48.png|icon-192.png|icon-512.png|apple-touch-icon.png)",
        headers: [{ key: "Cache-Control", value: ICON_CACHE }],
      },
    ];
  },
};

export default nextConfig;
